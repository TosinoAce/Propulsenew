-- APPLIED to the Supabase project on 2026-11-14 (as two migrations:
-- properties_public_read and inquiries_table_and_saved_owner_rule).

-- 1. Anyone, signed in or not, can browse properties
create policy "properties are publicly readable" on public.properties
  for select to anon using (true);

-- 2. Messages to realtors (property_id set) and general contact / waitlist messages (property_id null)
create table public.inquiries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  property_id bigint references public.properties(id) on delete set null,
  user_id uuid references auth.users(id) on delete set null,
  realtor_name text,
  name text not null check (char_length(name) between 1 and 200),
  email text not null check (char_length(email) between 3 and 320),
  phone text check (phone is null or char_length(phone) <= 40),
  message text not null check (char_length(message) between 1 and 5000)
);
create index inquiries_property_id_idx on public.inquiries(property_id);
create index inquiries_user_id_idx on public.inquiries(user_id);

alter table public.inquiries enable row level security;

create policy "anyone can send an inquiry" on public.inquiries
  for insert to anon, authenticated
  with check (user_id is null or user_id = (select auth.uid()));

create policy "senders and admins read inquiries" on public.inquiries
  for select to authenticated
  using (
    user_id = (select auth.uid())
    or exists (
      select 1 from public.user_profile p
      where p.auth_user = (select auth.uid()) and p.is_admin = true
    )
  );

-- 3. Saved properties: on top of the existing rules, each user can only touch their own rows
create policy "saved rows belong to their owner" on public."savedProperties"
  as restrictive for all to authenticated
  using ("userId" = (select auth.uid())::text)
  with check ("userId" = (select auth.uid())::text);
